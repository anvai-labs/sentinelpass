//! Run from the workspace root; --check is the CI drift gate.
use sentinelpass_protocol::custody::*;
use std::{fmt::Write as _, path::Path};

fn main() -> std::result::Result<(), Box<dyn std::error::Error>> {
    let check = std::env::args().any(|s| s == "--check");
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).parent().unwrap();
    let mut ts =
        String::from("// Generated by generate_custody_bindings; do not edit. Metadata only.\n");
    writeln!(ts, "export const CUSTODY_PROTOCOL = {PROTOCOL_VERSION} as const;\nexport const CUSTODY_FEATURE = {FEATURE_CUSTODY_V1} as const;")?;
    for (name, values) in ENUMS {
        writeln!(
            ts,
            "export type {name} = {};",
            values
                .iter()
                .map(|v| format!("'{v}'"))
                .collect::<Vec<_>>()
                .join(" | ")
        )?;
    }
    for schema in TYPES {
        writeln!(ts, "export interface {} {{", schema.name)?;
        for f in schema.fields {
            let ty = match f.rule {
                "version" => "1",
                "secretBytes" => "32",
                "bool" => "boolean",
                "id128" | "id512" | "decimal" | "sha256" => "string",
                name => name,
            };
            writeln!(ts, "  readonly {}: {ty};", f.name)?;
        }
        writeln!(ts, "}}")?;
    }
    ts.push_str("\n// Validate parsed metadata. Raw JSON is validated again in Rust, including duplicates.\nconst enums: Readonly<Record<string, readonly string[]>> = {\n");
    for (name, values) in ENUMS {
        writeln!(ts, "  {name}: {},", serde_json::to_string(values)?)?;
    }
    ts.push_str("};\nconst schemas = {\n");
    for schema in TYPES {
        writeln!(ts, "  {}: {{", schema.name)?;
        for f in schema.fields {
            writeln!(ts, "    {}: '{}',", f.name, f.rule)?;
        }
        ts.push_str("  },\n");
    }
    ts.push_str("} as const;\n");
    ts.push_str(include_str!("custody_validator.ts.in"));
    ts.push('\n');
    for schema in TYPES {
        writeln!(ts, "export function validate{}(value: unknown): value is {} {{ return validate('{}', value); }}", schema.name, schema.name, schema.name)?;
    }
    // Opaque types deliberately have no constructor or serializable authority.
    ts.push_str(include_str!("custody_ports.ts.in"));
    write(root, "bindings/custody/v1.ts", &ts, check)?;

    // Generated Kotlin wire DTOs; no keystore, lifecycle, crypto or usable provider.
    let mut kt = String::from("// Generated by generate_custody_bindings; do not edit.\npackage com.sentinelpass.custody\n\nimport kotlinx.serialization.Serializable\nimport kotlinx.serialization.SerialName\n\n");
    kt.push_str("object CustodyContract {\n");
    writeln!(kt, "    const val PROTOCOL: Int = {PROTOCOL_VERSION}\n    const val FEATURE: Int = {FEATURE_CUSTODY_V1}")?;
    kt.push_str("    // Metadata validation only. Load sentinelpass_mobile_bridge first.\n    @JvmStatic external fun validateMetadata(abi: Int, kind: Int, metadata: ByteArray): Int\n}\n");
    for (name, values) in ENUMS {
        writeln!(kt, "@Serializable\nenum class {name} {{")?;
        for value in *values {
            writeln!(
                kt,
                "    @SerialName(\"{value}\") {},",
                value.replace('-', "_").to_uppercase()
            )?;
        }
        kt.push_str("}\n");
    }
    for schema in TYPES {
        writeln!(kt, "@Serializable\ndata class {}(", schema.name)?;
        for f in schema.fields {
            let ty = match f.rule {
                "version" | "secretBytes" => "Int",
                "bool" => "Boolean",
                "id128" | "id512" | "decimal" | "sha256" => "String",
                name => name,
            };
            writeln!(kt, "    val {}: {ty},", f.name)?;
        }
        kt.push_str(")\n");
    }
    write(
        root,
        "android/SentinelPass/app/src/main/java/com/sentinelpass/custody/CustodyContract.kt",
        &kt,
        check,
    )?;
    // Swift consumes canonical JSON DTOs; native calls use the cbindgen header.
    let mut swift = String::from("// Generated by generate_custody_bindings; do not edit. Metadata only.\nimport Foundation\n\n");
    writeln!(swift, "enum CustodyContract {{\n    static let protocolVersion: UInt32 = {PROTOCOL_VERSION}\n    static let feature: UInt32 = {FEATURE_CUSTODY_V1}\n}}")?;
    for (name, values) in ENUMS {
        writeln!(swift, "enum {name}: String, Codable {{")?;
        for value in *values {
            let mut parts = value.split(['-', '_']);
            let mut name = parts.next().unwrap_or_default().to_string();
            for part in parts {
                let mut chars = part.chars();
                if let Some(first) = chars.next() {
                    name.extend(first.to_uppercase());
                }
                name.extend(chars);
            }
            writeln!(swift, "    case `{name}` = \"{value}\"")?;
        }
        swift.push_str("}\n");
    }
    for schema in TYPES {
        writeln!(swift, "struct {}: Codable {{", schema.name)?;
        for f in schema.fields {
            let ty = match f.rule {
                "version" | "secretBytes" => "UInt32",
                "bool" => "Bool",
                "id128" | "id512" | "decimal" | "sha256" => "String",
                name => name,
            };
            writeln!(swift, "    let `{}`: {ty}", f.name)?;
        }
        swift.push_str("}\n");
    }
    write(
        root,
        "bindings/custody/CustodyContract.swift",
        &swift,
        check,
    )?;
    // Package-local canonical fixtures also feed the cross-language copies.
    for (name, content) in [
        (
            "scope.golden.json",
            include_str!("../tests/fixtures/scope.golden.json"),
        ),
        (
            "reference.golden.json",
            include_str!("../tests/fixtures/reference.golden.json"),
        ),
        (
            "scope.array.invalid.json",
            include_str!("../tests/fixtures/scope.array.invalid.json"),
        ),
        (
            "reference.array.invalid.json",
            include_str!("../tests/fixtures/reference.array.invalid.json"),
        ),
        (
            "capabilities.array.invalid.json",
            include_str!("../tests/fixtures/capabilities.array.invalid.json"),
        ),
    ] {
        write(root, &format!("bindings/custody/{name}"), content, check)?;
    }
    Ok(())
}

fn write(
    root: &Path,
    path: &str,
    content: &str,
    check: bool,
) -> std::result::Result<(), Box<dyn std::error::Error>> {
    let path = root.join(path);
    if check {
        if std::fs::read_to_string(&path)? != content {
            return Err(format!("generated custody binding drift: {}", path.display()).into());
        }
    } else {
        std::fs::create_dir_all(path.parent().unwrap())?;
        std::fs::write(path, content)?;
    }
    Ok(())
}
